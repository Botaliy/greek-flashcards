VOWELS = set("αεηιουωάέήίόύώϊϋΐΰ")


def _adjective_forms(word: str) -> str:
    """καλός -> καλός, καλή, καλό; ωραίος -> ωραίος, ωραία, ωραίο."""
    if not word.endswith(("ος", "ός")):
        return ""
    stem, accented = word[:-2], word.endswith("ός")
    fem = ("ά" if accented else "α") if stem and stem[-1] in VOWELS else ("ή" if accented else "η")
    neu = "ό" if accented else "ο"
    return f"{word}, {stem}{fem}, {stem}{neu}"


def seed_rows():
    for group, text in GROUPS:
        words = []
        for line in text.strip().splitlines():
            parts = [p.strip() for p in line.split("|")]
            greek, russian = parts[0], parts[1]
            note = parts[2] if len(parts) > 2 else ""
            if group == "Прилагательные" and not note:
                note = _adjective_forms(greek)
            words.append((greek, russian, note))
        yield group, words
